package demo.lavka.entity;

import java.math.BigDecimal;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import jakarta.validation.constraints.DecimalMin;
import jakarta.validation.constraints.Digits;
import jakarta.validation.constraints.Min;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotNull;
import lombok.AccessLevel;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

// no @Data / @EqualsAndHashCode / @ToString on JPA entities: they break with a generated id and lazy relations
@Entity
@Table(name = "products")
@Getter
@NoArgsConstructor // for JPA
@AllArgsConstructor// only for @Builder
@Builder                                           // Products.builder().name(..).quantity(..).price(..).build()
public class Products {

    // no setter: the id is generated by the database
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Integer id;

    @Setter
    @NotBlank
    @Column(nullable = false)
    private String name;

    // how many items are in stock, never negative
    @Setter
    @Min(0)
    @Column(nullable = false)
    private int quantity;

    // BigDecimal, not double: money must not lose cents to rounding
    @Setter
    @NotNull
    @DecimalMin("0.00")
    @Digits(integer = 8, fraction = 2)
    @Column(nullable = false, precision = 10, scale = 2)
    private BigDecimal price;
}
